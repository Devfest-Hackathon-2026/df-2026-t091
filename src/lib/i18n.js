export function localizeNode(node, lang = 'en') {
  if (!node) return node;
  if (lang === 'ja') {
    return {
      ...node,
      title: node.titleJa || node.title,
      description: node.descriptionJa || node.description,
      resources: node.resourcesJa?.length ? node.resourcesJa : node.resources,
      restReason: node.restReasonJa || node.restReason,
    };
  }
  return node;
}

export function localizeRoadmap(roadmap, lang = 'en') {
  if (!roadmap) return roadmap;
  return {
    ...roadmap,
    goal: lang === 'ja' ? roadmap.goalJa || roadmap.goal : roadmap.goal,
    summary: lang === 'ja' ? roadmap.summaryJa || roadmap.summary : roadmap.summary,
    nodes: roadmap.nodes.map((n) => localizeNode(n, lang)),
  };
}
